func fixture(t *testing.T) []byte {
	t.Helper()
	b, err := os.ReadFile("testdata/manifest.json")
	if err != nil {
		t.Fatal(err)
	}
	return b
}
func sign(t *testing.T, m map[string]any) []byte {
	t.Helper()
	delete(m, "fingerprint")
	b, err := json.Marshal(m)
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(b)
	m["fingerprint"] = "sha256:" + hex.EncodeToString(sum[:])
	b, err = json.Marshal(m)
	if err != nil {
		t.Fatal(err)
	}
	return b
}
func object(t *testing.T) map[string]any {
	t.Helper()
	d := json.NewDecoder(bytes.NewReader(fixture(t)))
	d.UseNumber()
	var m map[string]any
	if err := d.Decode(&m); err != nil {
		t.Fatal(err)
	}
	return m
}
func TestActualGoGolden(t *testing.T) {
	data := fixture(t)
	a, err := Generate(data)
	if err != nil {
		t.Fatal(err)
	}
	b, err := Generate(data)
	if err != nil {
		t.Fatal(err)
	}
	golden, err := os.ReadFile("testdata/contracts.ts")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a, b) || !bytes.Equal(a, golden) {
		t.Fatal("generated bytes differ")
	}
	if bytes.Contains(a, []byte("unknown")) || bytes.Contains(a, []byte(" any")) {
		t.Fatal("unresolved types leaked")
	}
}
func TestInvalidManifestDiagnostics(t *testing.T) {
	cases := []struct {
		name, want string
		change     func(map[string]any)
	}{
		{"version", "schemaVersion", func(m map[string]any) { m["schemaVersion"] = "other" }},
		{"ref", "definitions.bad.ref", func(m map[string]any) {
			m["definitions"].(map[string]any)["bad"] = map[string]any{"kind": "ref", "ref": "absent"}
		}},
		{"kind", "definitions.bad", func(m map[string]any) {
			m["definitions"].(map[string]any)["bad"] = map[string]any{"kind": "unsupported"}
		}},
		{"cycle", "cyclic reference", func(m map[string]any) {
			m["definitions"].(map[string]any)["bad"] = map[string]any{"kind": "ref", "ref": "bad"}
		}},
		{"unsafe integer", "definitions.bad", func(m map[string]any) {
			m["definitions"].(map[string]any)["bad"] = map[string]any{"kind": "integer", "minimum": 0, "maximum": json.Number("9007199254740992")}
		}},
		{"irrelevant field", "definitions.bad.ref", func(m map[string]any) {
			m["definitions"].(map[string]any)["bad"] = map[string]any{"kind": "boolean", "ref": "absent"}
		}},
		{"canonical", "canonical.DispatchReceipt", func(m map[string]any) { delete(m["canonical"].(map[string]any), "DispatchReceipt") }},
		{"unknown", "unknown field", func(m map[string]any) { m["unexpected"] = true }},
		{"empty enum", "definitions.bad", func(m map[string]any) {
			m["definitions"].(map[string]any)["bad"] = map[string]any{"kind": "enum", "values": []string{}}
		}},
		{"invalid result mode", "resultMode", func(m map[string]any) {
			m["commands"].(map[string]any)["example.echo"].(map[string]any)["resultMode"] = "always"
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			m := object(t)
			tc.change(m)
			_, err := Generate(sign(t, m))
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("expected %s; got %v", tc.want, err)
			}
		})
	}
	data := fixture(t)
	data = bytes.Replace(data, []byte(`"rpc-contract/v1"`), []byte(`"rpc-contract/v1", "schemaVersion":"rpc-contract/v1"`), 1)
	if _, err := Generate(data); err == nil || !strings.Contains(err.Error(), "duplicate key") {
		t.Fatal(err)
	}
	m := object(t)
	m["fingerprint"] = "sha256:wrong"
	data, _ = json.Marshal(m)
	if _, err := Generate(data); err == nil || !strings.Contains(err.Error(), "fingerprint") {
		t.Fatal(err)
	}
	if _, err := Generate(append(fixture(t), []byte("{}")...)); err == nil {
		t.Fatal("trailing JSON accepted")
	}
}
func TestSupportedUnionAndEscapedProperty(t *testing.T) {
	m := object(t)
	m["definitions"].(map[string]any)["quoted\"name"] = map[string]any{"kind": "object", "properties": map[string]any{"quoted\"key": map[string]any{"required": true, "schema": map[string]any{"kind": "union", "variants": []any{map[string]any{"kind": "boolean"}, map[string]any{"kind": "null"}}}}}}
	b, err := Generate(sign(t, m))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(b), `"quoted\"key": (boolean) | (null)`) {
		t.Fatal(string(b))
	}
}

