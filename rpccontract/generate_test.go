func TestCommandIDsMatchDispatchCanonicalization(t *testing.T) {
	for _, id := range []string{" example.echo", "example.echo ", "\texample.echo\n", "\u00a0example.echo\u2003", " "} {
		t.Run(id, func(t *testing.T) {
			m := object(t)
			commands := m["commands"].(map[string]any)
			commands[id] = commands["example.echo"]
			if _, err := Generate(sign(t, m)); err == nil || !strings.Contains(err.Error(), "commands") {
				t.Fatalf("noncanonical command accepted: %v", err)
			}
		})
	}
	m := object(t)
	commands := m["commands"].(map[string]any)
	commands["example.interior space"] = commands["example.echo"]
	if _, err := Generate(sign(t, m)); err != nil {
		t.Fatal("interior space is part of the identity", err)
	}
	// Endpoint method names have separate registration rules; do not normalize them.
	m = object(t)
	endpoints := m["endpoints"].(map[string]any)
	endpoints[" spaced method "] = endpoints["example.echo"]
	if _, err := Generate(sign(t, m)); err != nil {
		t.Fatal(err)
	}
}
