package rpccontract

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"strings"
)

func quote(s string) string { b, _ := json.Marshal(s); return string(b) }
func typeName(id string) string {
	sum := sha256.Sum256([]byte(id))
	return "Type_" + hex.EncodeToString(sum[:12])
}
func ts(s WireSchema) string {
	var out string
	switch s.Kind {
	case "ref":
		out = typeName(s.Ref)
	case "json":
		out = "JsonValue"
	case "string":
		out = "string"
	case "boolean":
		out = "boolean"
	case "integer", "number":
		out = "number"
	case "null":
		out = "null"
	case "enum":
		parts := make([]string, len(s.Values))
		for i, v := range s.Values {
			parts[i] = quote(v)
		}
		out = strings.Join(parts, " | ")
	case "union":
		parts := make([]string, len(s.Variants))
		for i, v := range s.Variants {
			parts[i] = "(" + ts(v) + ")"
		}
		out = strings.Join(parts, " | ")
	case "array":
		if s.Length != nil {
			parts := make([]string, *s.Length)
			for i := range parts {
				parts[i] = ts(*s.Element)
			}
			out = "[" + strings.Join(parts, ", ") + "]"
		} else {
			out = "Array<" + ts(*s.Element) + ">"
		}
	case "map":
		out = "{ [key: string]: " + ts(*s.Element) + " }"
	case "object":
		parts := []string{}
		for _, k := range keys(s.Properties) {
			p := s.Properties[k]
			optional := ""
			if !p.Required {
				optional = "?"
			}
			parts = append(parts, quote(k)+optional+": "+ts(p.Schema)+";")
		}
		out = "{ " + strings.Join(parts, " ") + " }"
		if len(parts) == 0 {
			out = "{ [key: string]: never }"
		}
	}
	if s.Nullable && s.Kind != "null" && s.Kind != "json" {
		out = "(" + out + ") | null"
	}
	return out
}

// Generate is the reusable, side-effect-free manifest-to-TypeScript entry point.
// It interprets no Go types and imports no runtime application packages.
func Generate(data []byte) ([]byte, error) {
	m, err := Parse(data)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by rpc-contract-ts; DO NOT EDIT.\n// Contract fingerprint: %s\n\n", m.Fingerprint)
	b.WriteString("export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\nexport type SuccessEnvelope<T> = { data?: T };\n")
	for _, id := range keys(m.Definitions) {
		fmt.Fprintf(&b, "export type %s = %s;\n", typeName(id), ts(m.Definitions[id]))
	}
	for _, name := range []string{"RequestMeta", "Error", "DispatchOptions", "DispatchReceipt", "CommandDispatchRequest", "CommandDispatchResponse"} {
		fmt.Fprintf(&b, "export type %s = %s;\n", name, ts(m.Canonical[name]))
	}
	for _, kind := range []string{"MethodRequests", "MethodInputs", "MethodOutputs"} {
		fmt.Fprintf(&b, "\nexport interface %s {\n", kind)
		for _, id := range keys(m.Endpoints) {
			ep := m.Endpoints[id]
			n := ep.Request
			if kind == "MethodInputs" {
				r, _ := resolve(m, ep.Request)
				n = r.Properties["data"].Schema
			}
			if kind == "MethodOutputs" {
				r, _ := resolve(m, ep.Response)
				n = r.Properties["data"].Schema
			}
			fmt.Fprintf(&b, "  %s: %s;\n", quote(id), ts(n))
		}
		b.WriteString("}\n")
	}
	for _, kind := range []string{"CommandInputs", "CommandResults"} {
		fmt.Fprintf(&b, "\nexport interface %s {\n", kind)
		for _, id := range keys(m.Commands) {
			c := m.Commands[id]
			value := ts(c.Input)
			if kind == "CommandResults" {
				value = "never"
				if c.Result != nil {
					value = ts(*c.Result)
				}
			}
			fmt.Fprintf(&b, "  %s: %s;\n", quote(id), value)
		}
		b.WriteString("}\n")
	}
	b.WriteString(`
export type Method = keyof MethodInputs;
export type CommandID = keyof CommandInputs;
export type InvokeCallback = <K extends Method>(method: K, request: MethodRequests[K]) => Promise<SuccessEnvelope<MethodOutputs[K]>>;

// The binding calls its existing RPC client once. It owns error rejection.
export function createEndpoints(invoke: InvokeCallback) {
  return function call<K extends Method>(method: K, data: MethodInputs[K], meta?: RequestMeta): Promise<SuccessEnvelope<MethodOutputs[K]>> {
    return invoke<K>(method, { data, meta: meta ?? {} } as MethodRequests[K]);
  };
}

export type DispatchPayload<K extends CommandID> = Omit<CommandDispatchRequest, "command_id" | "payload" | "options"> & {
  command_id: K;
  payload: CommandInputs[K];
  options?: Partial<DispatchOptions>;
};
export type DispatchRequest<K extends CommandID> = { data: DispatchPayload<K>; meta?: RequestMeta };
export type DispatchResponse<K extends CommandID> = Omit<CommandDispatchResponse, "result"> & { result?: CommandResults[K] };
export type DispatchContext = { ids?: string[]; options?: Partial<DispatchOptions>; meta?: RequestMeta };
export type DispatchCallback = <K extends CommandID>(request: DispatchRequest<K>) => Promise<SuccessEnvelope<DispatchResponse<K>>>;

// This helper forwards the complete success envelope without unwrapping domain data.
export function createDispatcher(invoke: DispatchCallback) {
  return function dispatch<K extends CommandID>(commandID: K, payload: CommandInputs[K], context: DispatchContext = {}): Promise<SuccessEnvelope<DispatchResponse<K>>> {
    const data: DispatchPayload<K> = { command_id: commandID, payload };
    if (context.ids !== undefined) data.ids = context.ids;
    if (context.options !== undefined) data.options = context.options;
    const request: DispatchRequest<K> = { data };
    if (context.meta !== undefined) request.meta = context.meta;
    return invoke<K>(request);
  };
}
`)
	return []byte(b.String()), nil
}
